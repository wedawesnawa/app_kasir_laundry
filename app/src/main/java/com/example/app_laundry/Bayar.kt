package com.example.app_laundry

class Bayar {
    var id_bayar : Int = 0
    var total : Int = 0
    var id_order : Int = 0
    var cara_bayar : String =""
    var jumlah : Int = 0
    var status : String =""
    var allTotal : String=""


    constructor(){
        this.total
        this.id_order
        this.cara_bayar
        this.jumlah
        this.status
    }

    override fun toString(): String {
        return this.allTotal
    }
}